export const DICTIONARIES = { en, sv, de, es, hi };

let current = DEFAULT_LANGUAGE;

export function setLanguage(lang) {
  current = DICTIONARIES[lang] ? lang : DEFAULT_LANGUAGE;
  if (globalThis.document) document.documentElement.lang = current;
}

export function getLanguage() {
  return current;
}

function interpolate(s, vars) {
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k] ?? '') : m));
}

// Looks up `key` in the current language, falling back to English, then to the key itself.
export function t(key, vars = {}) {
  let v = DICTIONARIES[current][key] ?? en[key];
  if (v == null) return key;
  if (Array.isArray(v)) v = vars.n === 1 ? v[0] : v[1];
  return interpolate(v, vars);
}

// Translates a stored id such as a category ("cat", "Taxi"), keeping unknown values as they are.
export function label(prefix, id) {
  if (id == null || id === '') return '';
  const key = `${prefix}.${id}`;
  const v = DICTIONARIES[current][key] ?? en[key];
  return v ?? id;
}
